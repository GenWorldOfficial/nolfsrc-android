#!/usr/bin/env python3
"""A .dsp project's sources for one configuration, as absolute paths with the
case they have on disk (the project files spell them as Windows saw fit:
..\\lt2\\sdk\\inc\\ltquatbase.cpp for src/LT2/sdk/inc/ltquatbase.cpp).

    dspfiles.py <dsp2files.py> <project.dsp> <configuration> <extension>
"""

import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mkoverlay import find_real  # noqa: E402


def main():
    tool, dsp, config, ext = sys.argv[1:5]
    directory = os.path.dirname(os.path.abspath(dsp))
    out = subprocess.run([sys.executable, os.path.abspath(tool), os.path.abspath(dsp), config, ext],
                         cwd=directory, check=True, capture_output=True, text=True).stdout
    paths = []
    for name in out.split():
        real = find_real(directory, name)
        if not real:
            # generated by the build (the flex and bison outputs): the
            # build lists those itself
            print(f"dspfiles.py: {dsp}: no file for {name}, skipped", file=sys.stderr)
            continue
        if real not in paths:
            paths.append(real)
    print(";".join(paths))


if __name__ == "__main__":
    main()
